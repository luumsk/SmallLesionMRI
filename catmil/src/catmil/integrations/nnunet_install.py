"""``catmil-nnunet install | uninstall | status``: make the catmil trainers visible to nnU-Net.

``nnUNetv2_train -tr X`` only searches ``nnunetv2/training/nnUNetTrainer/``. ``install`` writes
one stub module there (``catmil_trainers.py``) that re-exports the catmil trainers; ``uninstall``
deletes it (only if it is our stub). Run it again after reinstalling or upgrading nnunetv2.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

STUB_NAME = "catmil_trainers.py"
MARKER = "# generated by catmil-nnunet install"
STUB = f'''{MARKER}; remove with: catmil-nnunet uninstall
from catmil.integrations.nnunet import *  # noqa: F401,F403
from catmil.integrations.nnunet import __all__  # noqa: F401
'''


def trainer_dir() -> Path:
    try:
        import nnunetv2
    except ImportError as e:
        raise SystemExit("nnunetv2 is not installed in this environment (pip install 'catmil[nnunet]')") from e
    return Path(nnunetv2.__path__[0]) / "training" / "nnUNetTrainer"


def _shadowing(d: Path):
    """Other modules in the trainer folder that define classes with our trainer names."""
    from catmil.integrations.nnunet import __all__ as names
    pat = re.compile(r"^class (%s)\(" % "|".join(names), re.M)
    hits = []
    for f in d.rglob("*.py"):
        if f.name == STUB_NAME:
            continue
        try:
            text = f.read_text(errors="ignore")
        except OSError:
            continue
        if "catmil.integrations.nnunet" in text:  # already a stub that imports from catmil
            continue
        hits += [(f, m) for m in pat.findall(text)]
    return hits


def install() -> int:
    d = trainer_dir()
    target = d / STUB_NAME
    if target.exists() and MARKER not in target.read_text():
        print(f"{target} exists and was not written by catmil; not touching it", file=sys.stderr)
        return 1
    target.write_text(STUB)
    print(f"installed {target}")
    for f, name in _shadowing(d):
        # nnU-Net imports modules in sorted order and takes the first match; ours sorts first
        # among lowercase names, but warn anyway so nobody trains the wrong class by accident.
        print(f"warning: {f} also defines {name}; consider replacing it with "
              f"'from catmil.integrations.nnunet import {name}'", file=sys.stderr)
    return 0


def uninstall() -> int:
    target = trainer_dir() / STUB_NAME
    if not target.exists():
        print("nothing to remove")
        return 0
    if MARKER not in target.read_text():
        print(f"{target} was not written by catmil; not removing it", file=sys.stderr)
        return 1
    target.unlink()
    print(f"removed {target}")
    return 0


def status() -> int:
    d = trainer_dir()
    target = d / STUB_NAME
    print(f"nnU-Net trainer folder: {d}")
    print(f"stub installed: {target.exists() and MARKER in target.read_text()}")
    from nnunetv2.utilities.find_class_by_name import recursive_find_python_class
    from catmil.integrations.nnunet import __all__ as names
    for n in names:
        cls = recursive_find_python_class(str(d), n, "nnunetv2.training.nnUNetTrainer")
        print(f"  {n:<28} -> {cls.__module__ if cls is not None else 'NOT FOUND'}")
    return 0


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="catmil-nnunet", description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=["install", "uninstall", "status"])
    args = ap.parse_args(argv)
    return {"install": install, "uninstall": uninstall, "status": status}[args.action]()


if __name__ == "__main__":
    sys.exit(main())
